"""Injectable LLM client abstraction and provider implementations.

Defines the BaseLLMClient interface allowing classification and generation
components to be tested independently of external model providers.
Implements LangChainGroqClient utilizing LangChain LCEL and ChatGroq.
"""

import logging
import re
from abc import ABC, abstractmethod
from typing import Any, cast

from langchain_core.callbacks import BaseCallbackHandler
from langchain_core.language_models.chat_models import BaseChatModel
from langchain_core.messages import AIMessage
from langchain_core.output_parsers import StrOutputParser
from langchain_core.outputs import LLMResult
from langchain_core.prompts import ChatPromptTemplate
from langchain_core.runnables import Runnable, RunnableConfig
from langchain_groq import ChatGroq
from pydantic import BaseModel, ConfigDict, Field, SecretStr

from cloudserve.config import Settings, get_settings

logger = logging.getLogger(__name__)


class LLMClientError(Exception):
    """Base exception for LLM client operations."""


class ConfigurationError(LLMClientError):
    """Raised when an LLM client is misconfigured (e.g. missing API key in live mode)."""


class LLMProviderError(LLMClientError):
    """Raised when an LLM provider encounters an error (timeout, rate limit, API failure)."""


class ProviderRateLimitError(LLMProviderError):
    """Raised on transient provider rate limits (e.g. HTTP 429 TPM/RPM throttling).

    Attributes:
        retry_after: Optional suggested wait time in seconds from Retry-After header.
    """

    def __init__(self, message: str, retry_after: float | None = None) -> None:
        super().__init__(message)
        self.retry_after = retry_after


class ProviderQuotaExhaustedError(LLMProviderError):
    """Raised when provider daily or account quota is exhausted (e.g. 200,000 TPD exceeded).

    Indicates that retrying immediately or with short exponential backoff will not succeed
    until the daily reset window.
    """

    def __init__(self, message: str, retry_after: float | None = None) -> None:
        super().__init__(message)
        self.retry_after = retry_after


def parse_retry_after(header_val: str | None) -> float | None:
    """Parse HTTP Retry-After header value into seconds."""
    if not header_val:
        return None
    try:
        val = float(header_val.strip())
        return max(0.0, val)
    except (ValueError, TypeError):
        return None


def is_daily_quota_exhaustion(error: Exception | str) -> bool:
    """Determine whether an error string indicates daily or persistent quota exhaustion.

    Distinguishes transient minute-level limits (TPM, RPM) from daily limits (TPD, credits).
    """
    msg = str(error).lower()
    quota_indicators = [
        "limit 200000",
        "tokens per day",
        "requests per day",
        "tpd",
        "rpd",
        "daily quota",
        "quota exceeded",
        "insufficient quota",
        "credit limit",
        "try again in",
    ]
    # Check if any indicator matches AND it indicates daily/hours wait rather than seconds
    for ind in quota_indicators:
        if ind in msg:
            # If msg indicates try again in hours or days, or explicit TPD/daily limit
            if any(term in msg for term in ["per day", "tpd", "rpd", "daily", "200000"]):
                return True
            # If retry-after or try again indicates hours or many minutes (e.g., 12h or 5h32m)
            if re.search(r"try again in \d+\s*(?:h|hr|hour|day)", msg):
                return True
            if "quota" in ind:
                return True
    return False


class LLMResponse(BaseModel):
    """Normalized response from an LLM call."""

    model_config = ConfigDict(frozen=True)

    content: str = Field(..., description="Raw text or JSON content generated by the model.")
    model_name: str = Field(..., description="Name or identifier of the generating model.")
    usage: dict[str, int] = Field(
        default_factory=dict,
        description="Token consumption metadata (prompt_tokens, completion_tokens).",
    )


class BaseLLMClient(ABC):
    """Abstract interface for LLM providers."""

    @abstractmethod
    def complete(
        self,
        prompt: str,
        system_prompt: str | None = None,
        temperature: float = 0.0,
        max_tokens: int = 1024,
        max_completion_tokens: int | None = None,
        **kwargs: Any,
    ) -> LLMResponse:
        """Execute a text completion or chat turn against the model provider."""

    @property
    @abstractmethod
    def model_name(self) -> str:
        """Return the active model name."""


class MockLLMClient(BaseLLMClient):
    """Deterministic mock LLM client for unit and integration tests.

    Allows injecting canned responses or sequential response queues without network calls.
    Mock completions report empty usage metadata by default since token consumption
    is not measured during testing, unless explicitly supplied.
    """

    def __init__(
        self,
        responses: list[str] | str = "",
        model_name: str = "mock-llm-v1",
        default_usage: dict[str, int] | None = None,
    ) -> None:
        if isinstance(responses, str):
            self._queue = [responses]
        else:
            self._queue = list(responses)
        self._default_model = model_name
        self._default_usage = dict(default_usage) if default_usage is not None else {}
        self.call_history: list[dict[str, Any]] = []

    def complete(
        self,
        prompt: str,
        system_prompt: str | None = None,
        temperature: float = 0.0,
        max_tokens: int = 1024,
        max_completion_tokens: int | None = None,
        **kwargs: Any,
    ) -> LLMResponse:
        """Return next queued response or echo prompt."""
        effective_tokens = (
            max_completion_tokens if max_completion_tokens is not None else max_tokens
        )
        self.call_history.append(
            {
                "prompt": prompt,
                "system_prompt": system_prompt,
                "temperature": temperature,
                "max_tokens": effective_tokens,
                "max_completion_tokens": effective_tokens,
                "kwargs": kwargs,
            }
        )
        if self._queue:
            content = self._queue.pop(0)
        else:
            content = "{}"
        return LLMResponse(
            content=content,
            model_name=self._default_model,
            usage=dict(self._default_usage),
        )

    @property
    def model_name(self) -> str:
        return self._default_model


def _extract_usage_metadata(message: Any) -> dict[str, int]:
    """Extract token consumption counts from provider metadata when present.

    Returns an empty dictionary if token usage metadata is not reported by the provider.
    """
    if hasattr(message, "response_metadata") and isinstance(message.response_metadata, dict):
        token_usage = message.response_metadata.get("token_usage")
        if isinstance(token_usage, dict):
            extracted = {}
            for k in ("prompt_tokens", "completion_tokens", "total_tokens"):
                if k in token_usage and isinstance(token_usage[k], (int, float)):
                    extracted[k] = int(token_usage[k])
            if extracted:
                return extracted

    if hasattr(message, "usage_metadata") and isinstance(message.usage_metadata, dict):
        extracted = {}
        for src_k, dst_k in (
            ("input_tokens", "prompt_tokens"),
            ("output_tokens", "completion_tokens"),
            ("total_tokens", "total_tokens"),
        ):
            if src_k in message.usage_metadata and isinstance(
                message.usage_metadata[src_k], (int, float)
            ):
                extracted[dst_k] = int(message.usage_metadata[src_k])
        if extracted:
            return extracted

    return {}


def _extract_model_name(message: Any, fallback_model: str) -> str:
    """Extract model name identifier from provider metadata when available."""
    if hasattr(message, "response_metadata") and isinstance(message.response_metadata, dict):
        model = message.response_metadata.get("model_name") or message.response_metadata.get(
            "model"
        )
        if model and isinstance(model, str) and model.strip():
            return model.strip()
    return fallback_model


class _MetadataCallbackHandler(BaseCallbackHandler):
    """Callback to capture raw AIMessage from ChatModel inside an LCEL chain."""

    def __init__(self) -> None:
        super().__init__()
        self.message: AIMessage | None = None

    def on_llm_end(self, response: LLMResult, **kwargs: Any) -> None:
        if response.generations and response.generations[0]:
            gen = response.generations[0][0]
            if hasattr(gen, "message") and isinstance(gen.message, AIMessage):
                self.message = gen.message


class LangChainGroqClient(BaseLLMClient):
    """LangChain-backed LLM client targeting Groq via LCEL.

    Executes completions using:
        ChatPromptTemplate | ChatGroq | StrOutputParser
    behind the existing BaseLLMClient interface, returning strongly-typed LLMResponse objects.
    """

    def __init__(
        self,
        api_key: str | SecretStr | None = None,
        model_name: str | None = None,
        settings: Settings | None = None,
        chat_model: BaseChatModel | None = None,
        timeout: float | None = None,
        max_retries: int | None = None,
        model_kwargs: dict[str, Any] | None = None,
    ) -> None:
        """Initialize LangChain Groq client.

        Args:
            api_key: Optional Groq API key override. If None, reads from settings.
            model_name: Optional target model name. If None, reads settings.groq_model.
            settings: Optional Settings instance. Defaults to get_settings().
            chat_model: Optional pre-configured BaseChatModel for offline tests/injection.
            timeout: Optional HTTP request timeout in seconds. Defaults to settings.groq_timeout.
            max_retries: Maximum number of retries on transient errors. Defaults to
                settings.groq_max_retries.
            model_kwargs: Optional additional model kwargs passed to ChatGroq. Defaults to
                {"include_reasoning": settings.groq_include_reasoning} to exclude reasoning output.

        Raises:
            ConfigurationError: If no valid Groq API key is found in live mode.
        """
        cfg = settings or get_settings()
        self._model_name = model_name or cfg.groq_model
        resolved_timeout = timeout if timeout is not None else cfg.groq_timeout
        resolved_max_retries = max_retries if max_retries is not None else cfg.groq_max_retries

        combined_model_kwargs = dict(model_kwargs) if model_kwargs is not None else {}
        if "include_reasoning" not in combined_model_kwargs:
            combined_model_kwargs["include_reasoning"] = cfg.groq_include_reasoning
        self._model_kwargs = combined_model_kwargs

        if chat_model is not None:
            self._chat_model = chat_model
        else:
            resolved_key: str | None = None
            if isinstance(api_key, SecretStr):
                resolved_key = api_key.get_secret_value()
            elif isinstance(api_key, str) and api_key.strip():
                resolved_key = api_key.strip()
            elif cfg.groq_api_key is not None:
                resolved_key = cfg.groq_api_key.get_secret_value().strip()

            if not resolved_key:
                raise ConfigurationError(
                    "Missing Groq API key: LangChainGroqClient requires a valid groq_api_key "
                    "in live mode. Set GROQ_API_KEY environment variable or pass api_key."
                )

            self._chat_model = ChatGroq(
                api_key=SecretStr(resolved_key),
                model=self._model_name,
                temperature=0.0,
                timeout=resolved_timeout,
                max_retries=resolved_max_retries,
                model_kwargs=self._model_kwargs,
            )

        self._prompt_template = ChatPromptTemplate.from_messages(
            [
                ("system", "{system_prompt}"),
                ("human", "{user_prompt}"),
            ]
        )
        self._output_parser = StrOutputParser()
        self._default_temperature = 0.0
        self._default_max_tokens = cfg.max_response_tokens
        self._pipeline = self._build_pipeline(
            temperature=self._default_temperature,
            max_tokens=self._default_max_tokens,
        )

    def _build_pipeline(
        self,
        temperature: float,
        max_tokens: int,
    ) -> Runnable[dict[str, Any], str]:
        """Construct LCEL pipeline with bound generation parameters and StrOutputParser.

        Binds max_completion_tokens (the modern non-deprecated token limit parameter for Groq)
        instead of deprecated max_tokens, ensuring exactly one token ceiling parameter is sent.
        """
        bound_model = self._chat_model.bind(
            temperature=temperature,
            max_completion_tokens=max_tokens,
        )
        return self._prompt_template | bound_model | self._output_parser

    @property
    def model_name(self) -> str:
        """Return the configured Groq model identifier."""
        return self._model_name

    @property
    def model_kwargs(self) -> dict[str, Any]:
        """Return the active model kwargs configured on the client."""
        return dict(self._model_kwargs)

    def complete(
        self,
        prompt: str,
        system_prompt: str | None = None,
        temperature: float = 0.0,
        max_tokens: int | None = None,
        max_completion_tokens: int | None = None,
        **kwargs: Any,
    ) -> LLMResponse:
        """Execute chat completion via LangChain LCEL pipeline and return normalized LLMResponse.

        Args:
            prompt: Formatted user prompt text (with delimiters already escaped).
            system_prompt: Optional system prompt instructions.
            temperature: Sampling temperature (0.0 for deterministic output).
            max_tokens: Token ceiling for model generation; mapped to max_completion_tokens.
            max_completion_tokens: Explicit non-deprecated token ceiling for Groq completions.
            **kwargs: Additional runtime arguments passed to invoke.

        Returns:
            LLMResponse containing raw response content, model name, and usage metadata.

        Raises:
            LLMProviderError: If the underlying model provider encounters a failure.
        """
        effective_system = system_prompt or "You are a helpful AI assistant."
        variables = {
            "system_prompt": effective_system,
            "user_prompt": prompt,
        }

        # Resolve token ceiling: prefer max_completion_tokens, fallback to max_tokens,
        # then central default
        resolved_limit = (
            max_completion_tokens
            if max_completion_tokens is not None
            else (max_tokens if max_tokens is not None else self._default_max_tokens)
        )

        try:
            # Execute stored pipeline when parameters match defaults;
            # construct parameterized chain when parameters change.
            if (
                temperature == self._default_temperature
                and resolved_limit == self._default_max_tokens
            ):
                pipeline = self._pipeline
            else:
                pipeline = self._build_pipeline(
                    temperature=temperature,
                    max_tokens=resolved_limit,
                )

            metadata_callback = _MetadataCallbackHandler()
            raw_config = kwargs.pop("config", None)
            invoke_config = cast(
                RunnableConfig,
                dict(raw_config) if isinstance(raw_config, dict) else {},
            )
            callbacks_list = list(invoke_config.get("callbacks") or [])  # type: ignore[arg-type]
            callbacks_list.append(metadata_callback)
            invoke_config["callbacks"] = callbacks_list

            content = pipeline.invoke(variables, config=invoke_config, **kwargs)

            actual_model = _extract_model_name(metadata_callback.message, self._model_name)
            usage = _extract_usage_metadata(metadata_callback.message)

            return LLMResponse(
                content=content,
                model_name=actual_model,
                usage=usage,
            )
        except Exception as exc:
            # Check for groq RateLimitError or 429
            retry_after_val: float | None = None
            is_429 = False

            # Inspect exception and its causes
            curr_exc: BaseException | None = exc
            while curr_exc is not None:
                status_code = getattr(curr_exc, "status_code", None)
                if status_code == 429 or "429" in str(curr_exc):
                    is_429 = True
                resp = getattr(curr_exc, "response", None)
                if resp is not None:
                    headers = getattr(resp, "headers", {})
                    if hasattr(headers, "get"):
                        ra = parse_retry_after(headers.get("retry-after"))
                        if ra is not None:
                            retry_after_val = ra
                curr_exc = curr_exc.__cause__

            if is_429 or is_daily_quota_exhaustion(exc):
                if is_daily_quota_exhaustion(exc):
                    logger.error(
                        "LangChainGroqClient: Daily quota exhausted for '%s': %s",
                        self._model_name,
                        exc,
                    )
                    raise ProviderQuotaExhaustedError(
                        f"Groq daily quota exhausted: {exc}",
                        retry_after=retry_after_val,
                    ) from exc

                logger.warning(
                    "LangChainGroqClient: Transient Groq 429 encountered (retry_after=%s): %s",
                    retry_after_val,
                    exc,
                )
                raise ProviderRateLimitError(
                    f"Groq rate limit exceeded: {exc}",
                    retry_after=retry_after_val,
                ) from exc

            logger.error(
                "LangChainGroqClient completion failed for model '%s': %s",
                self._model_name,
                exc,
            )
            raise LLMProviderError(f"Groq completion failed: {exc}") from exc


def get_llm_client(settings: Settings | None = None) -> BaseLLMClient:
    """Construct the appropriate LLM client based on application settings.

    In live production or staging mode, explicitly constructs LangChainGroqClient
    (raising ConfigurationError if GROQ_API_KEY is not configured).
    In testing or development mode without API key, returns MockLLMClient.
    """
    cfg = settings or get_settings()
    if cfg.environment in ("production", "staging"):
        return LangChainGroqClient(settings=cfg)
    if cfg.groq_api_key and cfg.groq_api_key.get_secret_value().strip():
        return LangChainGroqClient(settings=cfg)
    return MockLLMClient(model_name=cfg.groq_model)
